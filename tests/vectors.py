"""Published known-answer test vectors for every cipher in the repo.

This is the single source of truth for vector data: the unit tests under
``tests/`` and the harness ``examples/verify_vectors.py`` both
import from here, so a vector is only ever written down once.

Provenance
----------
AES       FIPS-197 C.1/C.2/C.3 and NIST SP 800-38A ECB/CBC.
DES       the classic published single-DES values (the FIPS 46-3 walkthrough
          pair, plus the two from the original DES paper's own test set). The
          ``AABB09182736CCDD`` entry is widely reproduced but does not appear
          in those sources, so its provenance is unconfirmed.
Blowfish  Schneier's 34-entry official ECB set and the official ``set_key``
          vectors for 4- to 24-byte keys. Keys under 4 bytes (32 bits) are
          outside the specification and are rejected, so the 1- to 3-byte
          ``set_key`` vectors are deliberately not used.
Twofish   the official KATs (Schneier et al., B.2) for 128/192/256-bit keys;
          the 128 chain continues the all-zero ciphertext as next plaintext.
Serpent   the official NESSIE/verified sets 1-4 for 128/192/256-bit keys as
          published by Biham et al., in little-endian octet order.
"""

