def named(triples, prefix):
    """Prefix (key, plaintext, ciphertext) triples with generated names."""
    return [(f"{prefix} {i}", k, p, c)
            for i, (k, p, c) in enumerate(triples)]


def programs():
    """Assemble every KAT collection keyed by the name used in the harness."""
    blowfish = named(BLOWFISH_OFFICIAL, "official")
    blowfish += [(f"set_key {len(k) * 4}", k, BLOWFISH_SET_KEY_PT, c)
                 for k, c in BLOWFISH_SET_KEY]
    return {
        "AES": AES_FIPS,
        "DES": named(DES_KATS, "des"),
        "Blowfish": blowfish,
        "Twofish": named(TWOFISH_KATS, "b2"),
        "Serpent": SERPENT_KATS,
    }
